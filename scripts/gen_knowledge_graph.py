HTML_END = "  // ===== KNOWLEDGE_GRAPH_DATA_END =====\n"

nodes = []
edges = []
_seen = set()


def add_node(node_id, label, group, **extra):
    if node_id in _seen:
        return
    _seen.add(node_id)
    nodes.append({"id": node_id, "label": label, "group": group, **extra})


def add_edge(a, b):
    edges.append({"from": a, "to": b})


