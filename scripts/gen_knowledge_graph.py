# ============================================================================ REPO INVENTORY (optional)
def scan_repo_inventory(xlsx_path, own_owner=None, untouched_top_n=30):
    """Optional layer: cross-reference the ~1500-repo inventory xlsx against INGESTION_LOG.md, plus the
    top-priority S-tier repos with NO log entry (real actionable backlog — 'repoBacklog' group). Pass
    own_owner (a GitHub username) to flag that owner's untouched repos distinctly ('repoOwn' group) —
    generic, no hardcoded identity. Best-effort — skipped gracefully if pandas/the file aren't available."""
    try:
        import pandas as pd
    except Exception:
        print("[gen_knowledge_graph] pandas unavailable — skipping repo-inventory layer")
        return 0
    if not xlsx_path or not os.path.exists(xlsx_path):
        return 0
    log_path = os.path.join(ROOT, "2_KNOWLEDGE", "INGESTION_LOG.md")
    rows, in_rejected = [], False
    for line in open(log_path, encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("## Rejected"):
            in_rejected = True
            continue
        if not line.startswith("|") or line.startswith("|---"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if in_rejected:
            if len(cells) >= 2 and cells[0] != "Source":
                rows.append({"source": cells[0], "what": cells[1], "where": "", "hint": "REJECTED"})
        elif len(cells) >= 4 and cells[1] != "Source":
            rows.append({"source": cells[1], "what": cells[3],
                         "where": cells[4] if len(cells) > 4 else "", "hint": None})

    def classify(what, where, hint):
        if hint:
            return hint
        w = what.upper()
        real_path = bool(re.search(r'(2_knowledge|4_brain|6_sop|7_assets|scripts/|1_agents|\.agents|3_memory)',
                                    where.lower())) and "none" not in where.lower() and "backlog" not in where.lower()
        if "SKIP-DUP" in w or (re.search(r'\bSKIP\b(?!PED)', w) and not real_path):
            return "SKIP"
        if "ADOPTED" in w or "ADOPT-PATTERN" in w or "BUILT" in w or real_path:
            return "BUILT"
        return "REFERENCE"

    pat = re.compile(r'\b([A-Za-z0-9][\w.-]*)/([A-Za-z0-9][\w.-]*)\b')
    candidates = []
    for r in rows:
        verdict = classify(r["what"], r["where"], r["hint"])
        for m in pat.finditer(r["source"]):
            candidates.append((m.group(1), m.group(2), verdict))

    df = pd.read_excel(xlsx_path, sheet_name="Repos_Classified")
    df["Owner_l"] = df["Owner"].astype(str).str.lower()
    df["Name_l"] = df["Name"].astype(str).str.lower()
    df["Repo_l"] = df["Repo/Model"].astype(str).str.lower()
    prio = {"BUILT": 3, "REFERENCE": 2, "SKIP": 1, "REJECTED": 1}
    matched = {}
    for o, n, v in candidates:
        hit = df[(df["Owner_l"] == o.lower()) & ((df["Name_l"] == n.lower()) | (df["Repo_l"] == n.lower()))]
        for idx in hit.index:
            if idx not in matched or prio.get(v, 0) >= prio.get(matched[idx], 0):
                matched[idx] = v

    inv_hub = "d_repoinv"
    add_node(inv_hub, f"Repo Inventory ({len(df)})", "dir")
    add_edge("d_2knowledge", inv_hub)
    cat_hub = {}
    for cat, grp in df.groupby("Category"):
        short = cat.split(" / ")[0].strip()
        cat_id = "rc_" + re.sub(r"\W+", "_", short)
        add_node(cat_id, f"{short} ({len(grp)})", "repocat")
        add_edge(inv_hub, cat_id)
        cat_hub[cat] = cat_id
    verdict_group = {"BUILT": "repoBuilt", "REFERENCE": "repoRef", "SKIP": "repoSkip", "REJECTED": "repoRej"}
    for idx, verdict in matched.items():
        row = df.loc[idx]
        node_id = f"rp_{row['Owner']}_{row['Name'].split('/')[-1]}"
        add_node(node_id, f"{row['Owner']}/{row['Name'].split('/')[-1]}", verdict_group[verdict])
        add_edge(cat_hub.get(row["Category"], inv_hub), node_id)

    # Actionable backlog: top-priority S-tier repos with NO log entry at all.
    try:
        top = pd.read_excel(xlsx_path, sheet_name="Top_Priority")
    except Exception:
        top = None
    n_untouched = 0
    if top is not None:
        matched_names = {df.loc[i, "Name"].lower() for i in matched}
        top["name_l"] = top["Name"].astype(str).str.lower()
        untouched = top[~top["name_l"].isin(matched_names)].sort_values("Priority Score", ascending=False)
        for _, row in untouched.head(untouched_top_n).iterrows():
            is_own = bool(own_owner) and str(row["Owner"]).lower() == own_owner.lower()
            node_id = f"ru_{row['Owner']}_{row['Name'].split('/')[-1]}"
            title = f"{row['Owner']}/{row['Name'].split('/')[-1]} — Priority {int(row['Priority Score'])}"
            if is_own:
                title += " — OWN REPO"
            add_node(node_id, f"{row['Owner']}/{row['Name'].split('/')[-1]}",
                      "repoOwn" if is_own else "repoBacklog", title=title)
            add_edge(cat_hub.get(row["Category"], inv_hub), node_id)
            n_untouched += 1
    return len(matched) + n_untouched


def sync_html():
    """Inject the CURRENT nodes/edges (single source of truth) into docs/SYSTEM_MAP.html between its
    markers, replacing the old hand-written duplicate. Best-effort — skipped if the file/markers are missing."""
    if not os.path.exists(HTML_PATH):
        print("[gen_knowledge_graph] SYSTEM_MAP.html not found — skipping HTML sync")
        return False
    html = open(HTML_PATH, encoding="utf-8").read()
    if HTML_START not in html or HTML_END not in html:
        print("[gen_knowledge_graph] WARNING: SYSTEM_MAP.html markers not found — HTML sync skipped "
              "(the graph view there is now STALE; check the markers weren't edited away)")
        return False
    pre, rest = html.split(HTML_START, 1)
    _, post = rest.split(HTML_END, 1)
    block = (HTML_START +
             f"  const nodes = {json.dumps(nodes, ensure_ascii=False)};\n"
             f"  const edges = {json.dumps(edges, ensure_ascii=False)};\n" +
             HTML_END)
    open(HTML_PATH, "w", encoding="utf-8").write(pre + block + post)
    print(f"[gen_knowledge_graph] synced {len(nodes)} nodes / {len(edges)} edges into {HTML_PATH}")
    return True


def main():
    ap = argparse.ArgumentParser(description="Generate SEOSONA's queryable knowledge graph")
    ap.add_argument("--inventory", help="optional path to repo_inventory xlsx (adds the repo layer)")
    ap.add_argument("--own-owner", help="GitHub username to flag distinctly among untouched backlog repos")
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--no-html-sync", action="store_true", help="skip updating docs/SYSTEM_MAP.html")
    a = ap.parse_args()

    scan_dirs()
    n_sop = scan_sops()
    n_brain = scan_brain_modules()
    n_pipelines = scan_pipelines()
    n_agents = scan_agents()
    n_skills = scan_skills()
    n_skill_modules = scan_skill_modules()
    n_templates = scan_templates()
    n_components = scan_components()
    n_effects = scan_effects()
    n_domain = scan_domain_skills()
    n_assets = scan_assets()
    n_repos = scan_repo_inventory(a.inventory, own_owner=a.own_owner)

    out = {"nodes": nodes, "edges": edges,
           "meta": {"generated": datetime.now().isoformat(timespec="seconds"),
                    "node_count": len(nodes), "edge_count": len(edges)}}
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    json.dump(out, open(a.out, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"[gen_knowledge_graph] {len(nodes)} nodes, {len(edges)} edges -> {a.out}")
    print(f"  SOPs:{n_sop}  brain-modules:{n_brain}  pipelines:{n_pipelines}  agents+personas:{n_agents}  "
          f"skills:{n_skills}  skill-modules:{n_skill_modules}  templates:{n_templates}  "
          f"components:{n_components}  effects:{n_effects}  "
          f"domain-skills:{n_domain}  assets:{n_assets}" + (f"  repos:{n_repos}" if n_repos else ""))
    if not a.no_html_sync:
        sync_html()


if __name__ == "__main__":
    main()
