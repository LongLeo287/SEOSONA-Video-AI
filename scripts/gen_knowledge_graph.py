"""Generate the SEOSONA Video knowledge graph — the machine-readable "second brain" data file.

Pattern harvested (REFERENCE-only, no vendoring — see 2_KNOWLEDGE/INGESTION_LOG.md 2026-07-01):
Karpathy's "LLM Wiki" (AgriciDaniel/claude-obsidian), obsidian-mind, code-review-graph, dreamgraph —
the shared insight: a knowledge graph should be QUERYABLE DATA an agent traverses to work faster, not
just a picture for humans. This script SCANS THE REAL REPO (SOPs, brain modules, agents, skills,
templates, components, effects) and emits `2_KNOWLEDGE/knowledge_graph.json` — the single source of
truth that `4_BRAIN/knowledge_graph.py` queries and that feeds `docs/SYSTEM_MAP.html`'s graph view.

Re-run this whenever the system changes (new SOP, new skill, new module) instead of hand-editing the
graph — this is what makes the graph "live" rather than a stale snapshot.

  python scripts/gen_knowledge_graph.py
  python scripts/gen_knowledge_graph.py --inventory "path/to/repo_inventory.xlsx"   # optional: also
      cross-reference the ~1500-repo inventory against INGESTION_LOG.md (adds a 'repo' layer)
"""
