NAME_TO_CAT = {n: cat for cat, names in SOP_CATS.items() for n in names}


def scan_sops():
    for cat, names in SOP_CATS.items():
        cat_id = "cat_" + cat
        add_node(cat_id, CAT_LABEL[cat], "sopcat")
        add_edge("d_6sop", cat_id)
    sop_dir = os.path.join(ROOT, "6_SOP")
    found, uncategorized = [], []
    for path in sorted(glob.glob(os.path.join(sop_dir, "*.md"))):
        stem = os.path.splitext(os.path.basename(path))[0]
        if stem.upper() == "README":
            continue
        found.append(stem)
        cat = NAME_TO_CAT.get(stem)
        if not cat:
            uncategorized.append(stem)
            cat = "sopInfra"  # safe fallback bucket; flagged below so it doesn't silently vanish
        node_id = "sop_" + stem
        add_node(node_id, stem, cat)
        add_edge("cat_" + cat, node_id)
    if uncategorized:
        print(f"[gen_knowledge_graph] WARNING: {len(uncategorized)} SOP(s) not in the curated category "
              f"map (filed under Infra as fallback) — update SOP_CATS: {uncategorized}")
    return len(found)


